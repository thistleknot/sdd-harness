"""| Stage | Mechanism | Tag | Requirements |
|---|---|---|---|
| GUARD | Reject every denylisted artifact before filesystem access | [mandatory] | R1 |
| READ | Read permitted existing files without changing bytes | [mandatory] | R1 |
| PLAN | Compute file, JSON merge, TOML/Markdown block, or TOML-key changes | [mandatory] | R2 |
| WRITE | Back up changed permitted files and replace them atomically | [mandatory] | R3 |

R1: When a denylisted path is supplied, the system shall reject it before any existence check or read.
R2: When a change is planned, the system shall preserve unowned namespaces and reject secret-looking keys.
R3: When changed existing bytes are written, the system shall save their preceding bytes before atomic replacement.

CLOSED: Loosening the Hermes credential-file deny rule is rejected; Hermes owns its native configuration writer and backups.
Preconditions: callers declare artifact ownership and mode; tests use isolated destinations and backup roots.
Failure modes: unsafe paths, malformed formats, or failed backups raise before replacement.
"""
from __future__ import annotations

import difflib
import json
import os
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

MODES = ("file", "jsonmerge", "tomlblock", "mdblock", "tomlkeys")

TOML_BEGIN = "# >>> harness party (generated by ~/.harness; edit tiers.toml, not this block) >>>"
TOML_END = "# <<< harness party <<<"
MD_BEGIN = "<!-- >>> harness party (generated by ~/.harness; edit tiers.toml, not this block) >>> -->"
MD_END = "<!-- <<< harness party <<< -->"

SECRET = re.compile(r"(?i)(api[_-]?key|apikey|token|secret|passw(or)?d|credential|bearer)")


class WriteError(RuntimeError):
    """Raised when a write would be unsafe or an artifact is malformed."""


@dataclass(frozen=True)
class Artifact:
    path: Path
    text: str
    mode: str = "file"
    note: str = ""
    owned_prefix: str = ""   # jsonmerge: patch keys with this prefix are ours and REPLACE what is there
    begin: str = ""          # tomlblock/mdblock: custom begin marker (default: the party marker)
    end: str = ""            # tomlblock/mdblock: custom end marker (default: the party marker)


@dataclass
class Change:
    artifact: Artifact
    before: str | None
    after: str
    warnings: list = field(default_factory=list)

    @property
    def status(self) -> str:
        if self.before is None:
            return "NEW"
        return "IDENTICAL" if self.before == self.after else "CHANGE"

    def diff(self) -> str:
        old = (self.before or "").splitlines(keepends=True)
        new = self.after.splitlines(keepends=True)
        return "".join(difflib.unified_diff(old, new, fromfile=f"{self.artifact.path} (current)",
                                            tofile=f"{self.artifact.path} (rendered)", n=2))


# --- paths and guards --------------------------------------------------------------------

def expand(path: str, root: Path) -> Path:
    """'~/x' is home-relative, a bare relative path is relative to the harness root."""
    if path.startswith("~"):
        return Path.home() / path[1:].lstrip("/\\")
    p = Path(path)
    return p if p.is_absolute() else root / p


def denied(path: Path) -> str | None:
    """Reason a file must never be opened or written, or None."""
    name = path.name.lower()
    flat = str(path).lower().replace("\\", "/")
    if "oh-my-opencode-slim" in name:
        return "the oh-my-opencode-slim plugin config owns its slots and rejects unknown keys"
    if name.startswith("litellm_config"):
        return "it holds provider API keys"
    if name == "config.yaml" and "/hermes" in flat:
        return "the hermes config holds api_key fields"
    return None


def assert_no_secret_keys(obj, where: str = "patch") -> None:
    """Reject any dict key, at any depth, that looks like a credential."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if SECRET.search(str(k)):
                raise WriteError(f"{where}: key {k!r} looks like a secret; refusing to write it")
            assert_no_secret_keys(v, where)
    elif isinstance(obj, list):
        for v in obj:
            assert_no_secret_keys(v, where)


def _assert_no_secret_toml_keys(text: str, where: str) -> None:
    for line in text.splitlines():
        m = re.match(r"^\s*([A-Za-z0-9_.\-\"]+)\s*=", line)
        if m and SECRET.search(m.group(1)):
            raise WriteError(f"{where}: key {m.group(1)!r} looks like a secret; refusing to write it")


# --- JSONC -------------------------------------------------------------------------------

def _strip_comments(text: str) -> str:
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif c == "/" and text[i:i + 2] == "//":
            while i < n and text[i] not in "\r\n":
                i += 1
        elif c == "/" and text[i:i + 2] == "/*":
            j = text.find("*/", i + 2)
            if j == -1:
                raise WriteError("unterminated /* comment in JSONC")
            i = j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _strip_trailing_commas(text: str) -> str:
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
        elif c == ",":
            j = i + 1
            while j < n and text[j] in " \t\r\n":
                j += 1
            if j < n and text[j] in "}]":
                i += 1
                continue
        out.append(c)
        i += 1
    return "".join(out)


def load_jsonc(text: str):
    """Parse JSON with // and /* */ comments and trailing commas. Raises WriteError, never guesses."""
    try:
        return json.loads(_strip_trailing_commas(_strip_comments(text)))
    except json.JSONDecodeError as exc:
        raise WriteError(f"cannot parse JSONC: {exc}") from exc


def deep_merge(base, patch, owned_prefix: str = ""):
    """Dicts merge recursively, everything else in `patch` replaces. Neither input is mutated.

    A patch key starting with `owned_prefix` is owned by the generator: it replaces the existing
    value wholesale, so a stale sub-key from an older render cannot survive beside the new one.
    """
    if isinstance(base, dict) and isinstance(patch, dict):
        out = dict(base)
        for k, v in patch.items():
            owned = bool(owned_prefix) and str(k).startswith(owned_prefix)
            out[k] = deep_merge(base[k], v, owned_prefix) if (k in base and not owned) else v
        return out
    return patch


# --- merges ------------------------------------------------------------------------------

def _lf(text: str) -> str:
    return text.replace("\r\n", "\n")


def _eol_like(existing: str | None, text: str) -> str:
    return text.replace("\n", "\r\n") if existing and "\r\n" in existing else text


def merge_json(existing: str | None, patch_text: str, owned_prefix: str = "") -> tuple:
    patch = json.loads(patch_text)
    assert_no_secret_keys(patch)
    warnings = []
    base = {}
    if existing is not None and existing.strip():
        base = load_jsonc(existing)
        if _strip_comments(existing) != existing:
            warnings.append("the existing file has comments; they are dropped on write")
    out = json.dumps(deep_merge(base, patch, owned_prefix), indent=2, ensure_ascii=False) + "\n"
    return _eol_like(existing, out), warnings


def merge_block(existing: str | None, block: str, begin: str, end: str) -> str:
    """Replace the begin..end block of `existing`, or append it. Content outside is untouched."""
    body = _lf(block).strip("\n")
    new = f"{begin}\n{body}\n{end}\n"
    if existing is None or not existing.strip():
        return _eol_like(existing, new)
    text = _lf(existing)
    has_begin, has_end = begin in text, end in text
    if has_begin != has_end:
        raise WriteError("found only one of the harness party markers; refusing to guess where the block is")
    if has_begin:
        a = text.index(begin)
        b = text.index(end, a) + len(end)
        if b < len(text) and text[b] == "\n":
            b += 1
        out = text[:a] + new + text[b:]
    else:
        out = text if text.endswith("\n") else text + "\n"
        out += "\n" + new
    return _eol_like(existing, out)


def set_toplevel_toml_keys(existing: str | None, keys: dict) -> str:
    """Set top-level keys (before the first [table]); values are already TOML literals."""
    text = _lf(existing or "")
    lines = text.splitlines()
    cut = next((i for i, ln in enumerate(lines) if re.match(r"^\s*\[", ln)), len(lines))
    head, tail = lines[:cut], lines[cut:]
    for key, literal in keys.items():
        pat = re.compile(rf"^\s*{re.escape(key)}\s*=")
        for i, ln in enumerate(head):
            if pat.match(ln):
                head[i] = f"{key} = {literal}"
                break
        else:
            at = max((i + 1 for i, ln in enumerate(head) if ln.strip()), default=0)
            head.insert(at, f"{key} = {literal}")
    out = "\n".join(head + tail) + "\n"
    return _eol_like(existing, out)


def compute(artifact: Artifact, existing: str | None) -> Change:
    """The text a file would have after applying `artifact`, without touching disk."""
    why = denied(artifact.path)
    if why:
        raise WriteError(f"refusing to touch {artifact.path}: {why}")
    if artifact.mode not in MODES:
        raise WriteError(f"unknown artifact mode {artifact.mode!r}")
    warnings: list = []
    if artifact.mode == "file":
        after = artifact.text
    elif artifact.mode == "jsonmerge":
        after, warnings = merge_json(existing, artifact.text, artifact.owned_prefix)
    elif artifact.mode == "tomlblock":
        _assert_no_secret_toml_keys(artifact.text, str(artifact.path))
        after = merge_block(existing, artifact.text, artifact.begin or TOML_BEGIN,
                            artifact.end or TOML_END)
    elif artifact.mode == "mdblock":
        after = merge_block(existing, artifact.text, artifact.begin or MD_BEGIN,
                            artifact.end or MD_END)
    else:
        keys = json.loads(artifact.text)
        assert_no_secret_keys(keys)
        after = set_toplevel_toml_keys(existing, keys)
    return Change(artifact, existing, after, warnings)


def read_existing(path: Path) -> str | None:
    """Read only a permitted destination, preserving original line endings.

    Args:
        path: Artifact destination inspected by adapters or plan.

    Returns:
        Existing text, or None when a permitted destination is absent.

    Require: Callers supply the final destination path.
    Guarantee: Denylisted paths fail before existence checks or reads.
    Maintain: This operation never changes filesystem content.
    Assert: The path guard precedes every filesystem operation.
    """
    why = denied(path)
    if why:
        raise WriteError(f"refusing to touch {path}: {why}")
    if not path.exists():
        return None
    with path.open("r", encoding="utf-8", newline="") as fh:
        return fh.read()


def plan(artifacts: list) -> list:
    """Preflight all destinations before reading any artifact in the batch.

    Args:
        artifacts: Ordered artifact batch supplied by an adapter.

    Returns:
        Computed changes without filesystem writes.

    Require: Each artifact declares its destination and merge mode.
    Guarantee: A denylisted destination rejects the batch before any file access.
    Maintain: Valid batches retain their input order.
    Assert: Path preflight completes before the first read_existing call.
    """
    for artifact in artifacts:
        why = denied(artifact.path)
        if why:
            raise WriteError(f"refusing to touch {artifact.path}: {why}")
    return [compute(a, read_existing(a.path)) for a in artifacts]


def apply(changes: list, backup_root: Path) -> list:
    """Back up each file that will change, then write atomically. Returns the paths written."""
    written = []
    for ch in changes:
        if ch.status == "IDENTICAL":
            continue
        path = ch.artifact.path
        why = denied(path)
        if why:
            raise WriteError(f"refusing to touch {path}: {why}")
        if ch.before is not None:
            flat = re.sub(r"[:\\/]+", "__", str(path))
            dest = backup_root / flat
            dest.parent.mkdir(parents=True, exist_ok=True)
            with dest.open("w", encoding="utf-8", newline="") as fh:
                fh.write(ch.before)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
                fh.write(ch.after)
            os.replace(tmp, path)
        except BaseException:
            if os.path.exists(tmp):
                os.unlink(tmp)
            raise
        written.append(path)
    return written
